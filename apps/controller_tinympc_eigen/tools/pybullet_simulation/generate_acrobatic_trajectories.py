#!/usr/bin/env python3
"""Generate chart-crossing Tier-3 flip trajectories for the PyBullet plant."""

from __future__ import annotations

import argparse
import csv
from dataclasses import dataclass
import math
from pathlib import Path

import numpy as np

from generate_banked_turn_trajectory import ARM, DT, G, MASS, YAW_RATIO, smooth


# The CF21B-500 motor/propeller measurements used by CrazySim top out at
# approximately 0.20 N per motor. Keeping the stored maneuver inside this
# independently measured envelope preserves differential torque authority for
# attitude feedback instead of asking the optimizer to recover from an
# infeasible collective-thrust reference.
ACRO_MAX_MOTOR_THRUST_N = 0.20
ACRO_REFERENCE_CEILING_N = 0.195
ACTUATOR_TRANSITION_S = 0.35
ACRO_INERTIA = np.diag([2.3951e-5, 2.3951e-5, 3.2347e-5])


@dataclass(frozen=True)
class AcrobaticManeuver:
    name: str
    description: str
    axis: tuple[float, float, float]
    rotation_deg: float = 360.0
    rotation_s: float = 0.60
    boost_s: float = 0.60
    recovery_s: float = 0.60
    boost_weight_multiplier: float = 1.412
    forward_barrel: bool = False


MANEUVERS = (
    AcrobaticManeuver(
        "roll_flip_360", "stationary full roll crossing the 180-degree chart boundary",
        (1.0, 0.0, 0.0),
    ),
    AcrobaticManeuver(
        "front_flip_360", "stationary full front flip crossing the 180-degree chart boundary",
        (0.0, 1.0, 0.0),
    ),
    AcrobaticManeuver(
        "backflip_360", "stationary full backflip crossing the 180-degree chart boundary",
        (0.0, -1.0, 0.0),
    ),
    AcrobaticManeuver(
        "barrel_roll_forward_360",
        "full roll while carrying forward velocity, with powered entry and braking exit",
        (1.0, 0.0, 0.0), rotation_s=1.20, boost_s=0.75,
        recovery_s=0.75, boost_weight_multiplier=1.63, forward_barrel=True,
    ),
)


def _allocation() -> np.ndarray:
    return np.asarray([
        [1.0, 1.0, 1.0, 1.0],
        [-ARM, -ARM, ARM, ARM],
        [-ARM, ARM, ARM, -ARM],
        [-YAW_RATIO, YAW_RATIO, -YAW_RATIO, YAW_RATIO],
    ])


def _axis_quaternion(axis: np.ndarray, angle: float) -> np.ndarray:
    return np.r_[math.cos(0.5 * angle), math.sin(0.5 * angle) * axis]


def _quaternion_rotation(quaternion_wxyz: np.ndarray) -> np.ndarray:
    w, x, y, z = quaternion_wxyz
    return np.asarray([
        [1.0 - 2.0 * (y * y + z * z), 2.0 * (x * y - z * w), 2.0 * (x * z + y * w)],
        [2.0 * (x * y + z * w), 1.0 - 2.0 * (x * x + z * z), 2.0 * (y * z - x * w)],
        [2.0 * (x * z - y * w), 2.0 * (y * z + x * w), 1.0 - 2.0 * (x * x + y * y)],
    ])


def _quaternion_product(left: np.ndarray, right: np.ndarray) -> np.ndarray:
    aw, ax, ay, az = left
    bw, bx, by, bz = right
    return np.asarray([
        aw * bw - ax * bx - ay * by - az * bz,
        aw * bx + ax * bw + ay * bz - az * by,
        aw * by - ax * bz + ay * bw + az * bx,
        aw * bz + ax * by - ay * bx + az * bw,
    ])


def _pulse(times: np.ndarray, start: float, end: float, amplitude: float) -> np.ndarray:
    phase = np.clip((times - start) / max(1.0e-9, end - start), 0.0, 1.0)
    return amplitude * np.sin(math.pi * phase) ** 2


def _transition(
    times: np.ndarray, start: float, end: float, before: float, after: float
) -> np.ndarray:
    phase = np.clip((times - start) / max(1.0e-9, end - start), 0.0, 1.0)
    blend = phase * phase * (3.0 - 2.0 * phase)
    return before + (after - before) * blend


def _float_literal(value: float) -> str:
    if abs(float(value)) < 5.0e-9:
        value = 0.0
    literal = f"{float(value):.8g}"
    if "." not in literal and "e" not in literal:
        literal += ".0"
    return literal + "f"


def _write_firmware_header(
    path: Path,
    maneuver: AcrobaticManeuver,
    times: np.ndarray,
    position: np.ndarray,
    quaternions: np.ndarray,
    velocity: np.ndarray,
    omega: np.ndarray,
    motors: np.ndarray,
    recovery_end_s: float,
) -> None:
    guard = f"TRAJ_{maneuver.name.upper()}_50HZ_H"
    samples = np.column_stack((position, quaternions, velocity, omega, motors))
    rows = [
        "  {" + ", ".join(_float_literal(value) for value in sample) + "},"
        for sample in samples
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join([
        "/* Autogenerated by generate_acrobatic_trajectories.py. */",
        f"#ifndef {guard}", f"#define {guard}", "",
        f'#define TRAJECTORY_NAME "{maneuver.name}"',
        "#define TRAJECTORY_SAMPLE_RATE_HZ 50",
        f"#define TRAJECTORY_SAMPLE_DT_S ({_float_literal(DT)})",
        f"#define TRAJECTORY_DURATION_S ({_float_literal(times[-1])})",
        f"#define TRAJECTORY_SAMPLE_COUNT {len(times)}",
        f"#define TRAJECTORY_RECOVERY_END_INDEX {int(round(recovery_end_s / DT))}",
        "#define TRAJECTORY_REFERENCE_DIM 17",
        "#define TRAJECTORY_LOOPS 0",
        "#define TRAJECTORY_TANGENT_HEADING 0",
        "#define TRAJECTORY_HAS_MOTOR_FEEDFORWARD 1",
        "",
        "// [p_W(3), q_WB(wxyz), v_W(3), omega_B(3), motor thrust N(4)]",
        "static const float trajectory_reference_data[TRAJECTORY_SAMPLE_COUNT][TRAJECTORY_REFERENCE_DIM] = {",
        *rows, "};", "", f"#endif  // {guard}", "",
    ]))


def generate(
    maneuver: AcrobaticManeuver,
    out: Path,
    initial_z_m: float = 1.1,
    firmware_header: Path | None = None,
) -> dict[str, float | str]:
    pre_s = 1.35 if maneuver.forward_barrel else 0.50
    boost_s = maneuver.boost_s
    recovery_s = maneuver.recovery_s
    settle_s = 2.20 if maneuver.forward_barrel else 1.20
    boost_ramp_start = pre_s
    boost_start = boost_ramp_start + ACTUATOR_TRANSITION_S
    boost_end = boost_start + boost_s
    rotation_ramp_start = boost_end
    rotation_start = rotation_ramp_start + ACTUATOR_TRANSITION_S
    rotation_end = rotation_start + maneuver.rotation_s
    recovery_start = rotation_end + ACTUATOR_TRANSITION_S
    recovery_end = recovery_start + recovery_s
    settle_start = recovery_end + ACTUATOR_TRANSITION_S
    duration = settle_start + settle_s
    times = np.arange(0.0, duration + 0.5 * DT, DT)
    axis = np.asarray(maneuver.axis, dtype=np.float64)
    axis /= np.linalg.norm(axis)
    angle = np.zeros_like(times)
    for index, timestamp in enumerate(times):
        if timestamp <= rotation_start:
            phase = 0.0
        elif timestamp >= rotation_end:
            phase = 1.0
        else:
            phase = (timestamp - rotation_start) / maneuver.rotation_s
        angle[index] = math.radians(maneuver.rotation_deg) * smooth(phase)
    angle_rate = np.gradient(angle, DT, edge_order=2)
    angle_acceleration = np.gradient(angle_rate, DT, edge_order=2)
    if maneuver.forward_barrel:
        entry_pitch = _pulse(times, 0.20, 1.05, math.radians(10.0))
        brake_start = recovery_end + 0.20
        brake_pitch = _pulse(
            times, brake_start, brake_start + 0.85, math.radians(-10.0)
        )
        pitch = entry_pitch + brake_pitch
        quaternions = np.asarray([
            _quaternion_product(
                _axis_quaternion(np.asarray([0.0, 1.0, 0.0]), pitch[index]),
                _axis_quaternion(axis, angle[index]),
            )
            for index in range(len(times))
        ])
    else:
        pitch = np.zeros_like(times)
        quaternions = np.asarray([_axis_quaternion(axis, value) for value in angle])
    rotations = np.asarray([_quaternion_rotation(quaternion) for quaternion in quaternions])
    omega = np.zeros((len(times), 3), dtype=np.float64)
    for index in range(len(times)):
        before = max(0, index - 1)
        after = min(len(times) - 1, index + 1)
        denominator = max(DT, float(times[after] - times[before]))
        relative = _quaternion_product(
            quaternions[before] * np.asarray([1.0, -1.0, -1.0, -1.0]),
            quaternions[after],
        )
        if relative[0] < 0.0:
            relative *= -1.0
        vector_norm = float(np.linalg.norm(relative[1:4]))
        if vector_norm > 1.0e-12:
            rotation_increment = (
                2.0 * math.atan2(vector_norm, float(relative[0]))
                * relative[1:4] / vector_norm
            )
            omega[index] = rotation_increment / denominator
    omega_dot = np.gradient(omega, DT, axis=0, edge_order=2)

    hover_total = MASS * G
    boost_total = maneuver.boost_weight_multiplier * hover_total
    coast_total = 0.28 * hover_total

    def collective_profile(recovery_total: float) -> np.ndarray:
        result = np.full(len(times), hover_total)
        ramp = (times >= boost_ramp_start) & (times < boost_start)
        result[ramp] = _transition(
            times[ramp], boost_ramp_start, boost_start, hover_total, boost_total
        )
        result[(times >= boost_start) & (times < boost_end)] = boost_total
        ramp = (times >= rotation_ramp_start) & (times < rotation_start)
        result[ramp] = _transition(
            times[ramp], rotation_ramp_start, rotation_start, boost_total, coast_total
        )
        result[(times >= rotation_start) & (times < rotation_end)] = coast_total
        ramp = (times >= rotation_end) & (times < recovery_start)
        result[ramp] = _transition(
            times[ramp], rotation_end, recovery_start, coast_total, recovery_total
        )
        result[(times >= recovery_start) & (times < recovery_end)] = recovery_total
        ramp = (times >= recovery_end) & (times < settle_start)
        result[ramp] = _transition(
            times[ramp], recovery_end, settle_start, recovery_total, hover_total
        )
        if maneuver.forward_barrel:
            result /= np.maximum(0.25, np.cos(pitch))
        return result

    collective = collective_profile(hover_total)

    def propagate(candidate: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        candidate_acceleration = np.asarray([
            rotations[index] @ np.asarray([0.0, 0.0, candidate[index] / MASS])
            - np.asarray([0.0, 0.0, G])
            for index in range(len(times))
        ])
        candidate_velocity = np.zeros((len(times), 3), dtype=np.float64)
        candidate_position = np.zeros((len(times), 3), dtype=np.float64)
        candidate_position[0, 2] = float(initial_z_m)
        for index in range(1, len(times)):
            candidate_velocity[index] = candidate_velocity[index - 1] + 0.5 * DT * (
                candidate_acceleration[index - 1] + candidate_acceleration[index]
            )
            candidate_position[index] = candidate_position[index - 1] + 0.5 * DT * (
                candidate_velocity[index - 1] + candidate_velocity[index]
            )
        return candidate_acceleration, candidate_velocity, candidate_position

    # Choose the level recovery collective so the ballistic maneuver exits
    # with zero vertical speed instead of hiding a discontinuity in the
    # reference's final hover segment.
    recovery_end_index = int(np.searchsorted(times, settle_start, side="left"))
    lower, upper = hover_total, 4.0 * ACRO_REFERENCE_CEILING_N
    for _ in range(50):
        candidate_value = 0.5 * (lower + upper)
        collective = collective_profile(candidate_value)
        _, candidate_velocity, _ = propagate(collective)
        if candidate_velocity[recovery_end_index, 2] < 0.0:
            lower = candidate_value
        else:
            upper = candidate_value
    collective = collective_profile(0.5 * (lower + upper))

    moments = np.zeros((len(times), 3), dtype=np.float64)
    for index in range(len(times)):
        moments[index] = ACRO_INERTIA @ omega_dot[index]
        moments[index] += np.cross(omega[index], ACRO_INERTIA @ omega[index])
    mixer = _allocation()
    motors = np.asarray([
        np.linalg.solve(mixer, np.r_[collective[index], moments[index]])
        for index in range(len(times))
    ])
    maximum = ACRO_MAX_MOTOR_THRUST_N
    if float(np.min(motors)) < -1.0e-8 or float(np.max(motors)) > maximum + 1.0e-8:
        raise RuntimeError(
            f"{maneuver.name} feedforward is infeasible: {motors.min():.4f}.."
            f"{motors.max():.4f} N; motor limit is {maximum:.4f} N"
        )

    acceleration, velocity, position = propagate(collective)

    out.parent.mkdir(parents=True, exist_ok=True)
    fields = [
        "t", "x", "y", "z", "vx", "vy", "vz", "qw", "qx", "qy", "qz",
        "wx", "wy", "wz", *[f"motor_{index}_thrust_n" for index in range(4)],
    ]
    with out.open("w", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerow(fields)
        for index, timestamp in enumerate(times):
            writer.writerow([
                f"{timestamp:.9f}", *position[index], *velocity[index],
                *quaternions[index], *omega[index], *motors[index],
            ])
    if firmware_header is not None:
        _write_firmware_header(
            firmware_header, maneuver, times, position, quaternions,
            velocity, omega, motors, recovery_end,
        )
    return {
        "name": maneuver.name,
        "description": maneuver.description,
        "trajectory": str(out),
        "duration_s": float(times[-1]),
        "rotation_deg": float(maneuver.rotation_deg),
        "peak_body_rate_deg_s": math.degrees(float(np.max(np.abs(angle_rate)))),
        "peak_forward_velocity_mps": float(np.max(velocity[:, 0])),
        "minimum_reference_z_m": float(np.min(position[:, 2])),
        "maximum_reference_z_m": float(np.max(position[:, 2])),
        "final_reference_z_m": float(position[-1, 2]),
        "min_feedforward_motor_thrust_n": float(np.min(motors)),
        "max_feedforward_motor_thrust_n": float(np.max(motors)),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", type=Path, default=Path("sim/trajectories/acrobatics"))
    parser.add_argument("--maneuver", action="append", choices=[item.name for item in MANEUVERS])
    parser.add_argument("--initial-z", type=float, default=1.1)
    parser.add_argument("--firmware-header-dir", type=Path)
    args = parser.parse_args()
    selected = set(args.maneuver or [item.name for item in MANEUVERS])
    for maneuver in MANEUVERS:
        if maneuver.name not in selected:
            continue
        firmware_header = (
            args.firmware_header_dir / f"traj_{maneuver.name}_50hz.h"
            if args.firmware_header_dir is not None else None
        )
        result = generate(
            maneuver, args.out_dir / f"{maneuver.name}.csv",
            float(args.initial_z), firmware_header,
        )
        print(
            f"wrote {result['trajectory']}: rate={result['peak_body_rate_deg_s']:.1f}deg/s, "
            f"z={result['minimum_reference_z_m']:.2f}..{result['maximum_reference_z_m']:.2f}m, "
            f"motor={result['min_feedforward_motor_thrust_n']:.3f}.."
            f"{result['max_feedforward_motor_thrust_n']:.3f}N"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
