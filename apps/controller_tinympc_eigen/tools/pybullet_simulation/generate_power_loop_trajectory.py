#!/usr/bin/env python3
"""Generate a compact, actuator-feasible vertical power-loop reference."""

from __future__ import annotations

import argparse
import csv
import math
from pathlib import Path

import numpy as np


DT = 0.02
G = 9.81
MASS_KG = 0.04338
PITCH_INERTIA_KGM2 = 2.8e-5
ARM_M = 0.035355
MAX_MOTOR_THRUST_N = 0.20


def minimum_jerk_phase(value: np.ndarray) -> np.ndarray:
    """Map [0, 1] to [0, 1] with zero velocity and acceleration at both ends."""
    return 10.0 * value**3 - 15.0 * value**4 + 6.0 * value**5


def minimum_jerk_phase_rate(value: np.ndarray) -> np.ndarray:
    return 30.0 * value**2 * (1.0 - value)**2


def minimum_jerk_phase_acceleration(value: np.ndarray) -> np.ndarray:
    return 60.0 * value - 180.0 * value**2 + 120.0 * value**3


def _float_literal(value: float) -> str:
    if abs(float(value)) < 5.0e-9:
        value = 0.0
    literal = f"{float(value):.8g}"
    if "." not in literal and "e" not in literal:
        literal += ".0"
    return literal + "f"


def _write_header(
    path: Path, times: np.ndarray, position: np.ndarray,
    quaternions: np.ndarray, velocity: np.ndarray, omega: np.ndarray,
    motors: np.ndarray,
) -> None:
    samples = np.column_stack((position, quaternions, velocity, omega, motors))
    rows = [
        "  {" + ", ".join(_float_literal(value) for value in sample) + "},"
        for sample in samples
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join([
        "/* Autogenerated by generate_power_loop_trajectory.py. */",
        "#ifndef TRAJ_REACTIVE_POWER_LOOP_360_50HZ_H",
        "#define TRAJ_REACTIVE_POWER_LOOP_360_50HZ_H", "",
        '#define TINYMPC_REACTIVE_LOOP_TRAJECTORY_NAME "power_loop_vertical_360"',
        "#define TINYMPC_REACTIVE_LOOP_SAMPLE_RATE_HZ 50",
        f"#define TINYMPC_REACTIVE_LOOP_SAMPLE_DT_S ({_float_literal(DT)})",
        f"#define TINYMPC_REACTIVE_LOOP_DURATION_S ({_float_literal(times[-1])})",
        f"#define TINYMPC_REACTIVE_LOOP_SAMPLE_COUNT {len(times)}",
        f"#define TINYMPC_REACTIVE_LOOP_MIN_RELATIVE_X_M ({_float_literal(np.min(position[:, 0] - position[0, 0]))})",
        f"#define TINYMPC_REACTIVE_LOOP_MAX_RELATIVE_X_M ({_float_literal(np.max(position[:, 0] - position[0, 0]))})",
        f"#define TINYMPC_REACTIVE_LOOP_MIN_RELATIVE_Y_M ({_float_literal(np.min(position[:, 1] - position[0, 1]))})",
        f"#define TINYMPC_REACTIVE_LOOP_MAX_RELATIVE_Y_M ({_float_literal(np.max(position[:, 1] - position[0, 1]))})",
        f"#define TINYMPC_REACTIVE_LOOP_MAX_RELATIVE_Z_M ({_float_literal(np.max(position[:, 2] - position[0, 2]))})",
        "#define TINYMPC_REACTIVE_LOOP_REFERENCE_DIM 17", "",
        "// [p_W(3), q_WB(wxyz), v_W(3), omega_B(3), motor thrust N(4)]",
        "static const float tinympc_reactive_loop_reference_data[TINYMPC_REACTIVE_LOOP_SAMPLE_COUNT][TINYMPC_REACTIVE_LOOP_REFERENCE_DIM] = {",
        *rows, "};", "", "#endif", "",
    ]))


def generate(
    output_csv: Path, output_header: Path | None, initial_z_m: float,
    radius_m: float, peak_speed_mps: float, hold_s: float, settle_s: float,
) -> dict[str, float | int | str]:
    if radius_m <= 0.0 or peak_speed_mps <= 0.0:
        raise ValueError("radius and peak speed must be positive")
    # The quintic phase derivative peaks at 1.875 when phase=0.5. Choose the
    # loop time so the trajectory reaches the requested speed while inverted.
    nominal_loop_s = 2.0 * math.pi * radius_m * 1.875 / peak_speed_mps
    loop_intervals = max(1, int(round(nominal_loop_s / DT)))
    loop_s = loop_intervals * DT

    hold_intervals = int(round(hold_s / DT))
    settle_intervals = int(round(settle_s / DT))
    loop_start = hold_intervals
    settle_start = loop_start + loop_intervals
    intervals = settle_start + settle_intervals
    times = np.arange(intervals + 1, dtype=np.float64) * DT

    position = np.zeros((len(times), 3), dtype=np.float64)
    position[:, 2] = initial_z_m
    velocity = np.zeros((len(times), 3), dtype=np.float64)
    acceleration = np.zeros((len(times), 3), dtype=np.float64)

    normalized_time = np.arange(loop_intervals + 1) / loop_intervals
    alpha = 2.0 * math.pi * minimum_jerk_phase(normalized_time)
    alpha_rate = (2.0 * math.pi / loop_s
                  * minimum_jerk_phase_rate(normalized_time))
    alpha_acceleration = (2.0 * math.pi / loop_s**2
                          * minimum_jerk_phase_acceleration(normalized_time))
    speed = radius_m * alpha_rate
    loop_slice = slice(loop_start, settle_start + 1)
    position[loop_slice, 0] = radius_m * np.sin(alpha)
    position[loop_slice, 2] = initial_z_m + radius_m * (1.0 - np.cos(alpha))
    velocity[loop_slice, 0] = speed * np.cos(alpha)
    velocity[loop_slice, 2] = speed * np.sin(alpha)
    acceleration[loop_slice, 0] = (
        radius_m * alpha_acceleration * np.cos(alpha)
        - radius_m * alpha_rate**2 * np.sin(alpha))
    acceleration[loop_slice, 2] = (
        radius_m * alpha_acceleration * np.sin(alpha)
        + radius_m * alpha_rate**2 * np.cos(alpha))

    required_acceleration = acceleration.copy()
    required_acceleration[:, 2] += G
    pitch = np.unwrap(np.arctan2(
        required_acceleration[:, 0], required_acceleration[:, 2]))
    collective = MASS_KG * np.linalg.norm(required_acceleration, axis=1)
    quaternions = np.zeros((len(times), 4), dtype=np.float64)
    quaternions[:, 0] = np.cos(0.5 * pitch)
    quaternions[:, 2] = np.sin(0.5 * pitch)
    omega = np.zeros((len(times), 3), dtype=np.float64)
    omega[:, 1] = np.gradient(pitch, DT, edge_order=2)
    pitch_acceleration = np.gradient(omega[:, 1], DT, edge_order=2)
    differential = PITCH_INERTIA_KGM2 * pitch_acceleration / (4.0 * ARM_M)
    motors = np.column_stack((
        collective / 4.0 - differential,
        collective / 4.0 + differential,
        collective / 4.0 + differential,
        collective / 4.0 - differential,
    ))
    if (float(np.min(motors)) < -1.0e-8 or
            float(np.max(motors)) > MAX_MOTOR_THRUST_N):
        raise RuntimeError(
            f"power-loop feedforward is infeasible: {motors.min():.4f}.."
            f"{motors.max():.4f} N exceeds the "
            f"{MAX_MOTOR_THRUST_N:.4f} N motor limit")

    output_csv.parent.mkdir(parents=True, exist_ok=True)
    fields = [
        "t", "x", "y", "z", "vx", "vy", "vz", "qw", "qx", "qy", "qz",
        "wx", "wy", "wz", *[f"motor_{index}_thrust_n" for index in range(4)],
    ]
    with output_csv.open("w", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerow(fields)
        for index, timestamp in enumerate(times):
            writer.writerow([
                f"{timestamp:.9f}", *position[index], *velocity[index],
                *quaternions[index], *omega[index], *motors[index],
            ])
    if output_header is not None:
        _write_header(
            output_header, times, position, quaternions, velocity, omega, motors)
    return {
        "trajectory": str(output_csv), "samples": len(times),
        "duration_s": float(times[-1]), "loop_duration_s": loop_s,
        "effective_peak_speed_mps": float(np.max(np.linalg.norm(velocity, axis=1))),
        "maximum_relative_z_m": float(np.max(position[:, 2]) - initial_z_m),
        "final_relative_x_m": float(position[-1, 0]),
        "minimum_motor_thrust_n": float(np.min(motors)),
        "maximum_motor_thrust_n": float(np.max(motors)),
        "peak_pitch_rate_rad_s": float(np.max(np.abs(omega[:, 1]))),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--firmware-header", type=Path)
    parser.add_argument("--initial-z", type=float, default=1.1)
    parser.add_argument("--radius", type=float, default=1.0)
    parser.add_argument("--peak-speed", type=float, default=3.8)
    parser.add_argument("--hold-s", type=float, default=0.5)
    parser.add_argument("--settle-s", type=float, default=1.2)
    args = parser.parse_args()
    result = generate(
        args.out, args.firmware_header, args.initial_z, args.radius,
        args.peak_speed, args.hold_s, args.settle_s)
    for key, value in result.items():
        print(f"{key}: {value}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
